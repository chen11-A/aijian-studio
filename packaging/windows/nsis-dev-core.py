def digest(path: Path) -> str:
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def literal(value: str) -> str:
    if any(ord(character) < 32 for character in value):
        raise ValueError("Control characters cannot appear in an installer path")
    return '"' + value.replace("$", "$$").replace('"', '$\\"') + '"'


def program_files(app: Path) -> dict[str, str]:
    files = {}
    for path in sorted(app.rglob("*")):
        if path.is_symlink() or path.is_junction():
            raise ValueError("Installed program tree cannot contain a link or junction")
        if path.is_file():
            relative = path.relative_to(app).as_posix()
            if any(part in {"", ".", ".."} for part in relative.split("/")) or ":" in relative:
                raise ValueError("Unsafe installed program path")
            if relative.lower() == "uninstall.exe":
                raise ValueError("Input collides with the generated uninstaller")
            files[relative] = digest(path)
        elif not path.is_dir():
            raise ValueError("Installer only accepts plain files/directories")
    if PRODUCT + ".exe" not in files:
        raise ValueError("The packaged development application executable is absent")
    return files


