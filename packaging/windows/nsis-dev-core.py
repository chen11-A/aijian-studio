def build(stage: Path, tools: dict, evidence: Path) -> Path:
    app = stage / "installer-output/win-unpacked"
    installer = stage / "installer-output" / INSTALLER_FILENAME
    if installer.exists():
        raise ValueError("Refusing to overwrite an existing installer")
    nsis = Path(tools["environment"]["ELECTRON_BUILDER_NSIS_DIR"])
    if digest(nsis / "COPYING") != NSIS_COPYING_SHA256:
        raise ValueError("Pinned NSIS core licence material changed")
    script, files = generate_script(app, installer, stage / "build/installer.nsh")
    script_path = stage / "build/development-core.nsi"
    script_path.write_text(script, encoding="utf-8-sig")
    # Compiler bytes originate from the already SHA-verified official NSIS archive.
    compiler = nsis / "Bin/makensis.exe"
    if digest(compiler) != NSIS_WINDOWS_COMPILER_SHA256:
        raise ValueError("Pinned NSIS compiler bytes changed")
    subprocess.run(
        [str(compiler), "/V2", str(script_path)],
        check=True,
        cwd=stage / "build",
        env={**os.environ, "NSISDIR": str(nsis)},
    )
    if program_files(app) != files:
        raise ValueError("Packaged application files changed during installer compilation")
    receipt = {
        "schema_version": 1,
        "profile": "DEVELOPMENT_CORE",
        "installer_engine": "first-party-nsis-core-zlib",
        "nsis_version": "3.0.4.1",
        "nsis_copying_sha256": NSIS_COPYING_SHA256,
        "compiler_sha256": digest(compiler),
        "script_sha256": digest(script_path),
        "hook_sha256": digest(stage / "build/installer.nsh"),
        "installed_program_files": files,
        "installer_sha256": digest(installer),
        "installer_bytes": installer.stat().st_size,
        "third_party_resource_plugins": [],
        "uninstall": "explicit-program-file-list-and-empty-directories-only",
        "existing_install_or_data": "PRESERVED",
        "display_name": PRODUCT,
        "display_version": PRODUCT_VERSION,
        "user_data_folder": USER_DATA_FOLDER,
        "release_approved": False,
    }
    (evidence / "NSIS-CORE-BUILD.json").write_text(json.dumps(receipt, indent=2) + "\n")
    return installer


def verify(stage: Path, receipt: dict) -> None:
    if (
        receipt.get("schema_version") != 1
        or receipt.get("profile") != "DEVELOPMENT_CORE"
        or receipt.get("installer_engine") != "first-party-nsis-core-zlib"
        or receipt.get("third_party_resource_plugins") != []
        or receipt.get("compiler_sha256") != NSIS_WINDOWS_COMPILER_SHA256
        or receipt.get("release_approved") is not False
        or receipt.get("existing_install_or_data") != "PRESERVED"
        or receipt.get("display_name") != PRODUCT
        or receipt.get("display_version") != PRODUCT_VERSION
        or receipt.get("user_data_folder") != USER_DATA_FOLDER
    ):
        raise ValueError("Expected the pinned plugin-free Windows installer build receipt")
